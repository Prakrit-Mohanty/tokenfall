#!/usr/bin/env node
// Turns the models and sprite sheets that are embedded as base64 text in js/models/*.js and js/sprites/chars-sheet.js into binary files
// the game fetches over http(s) (see js/asset-files.js):
//
//   assets/models/car-<kind>.glb    from js/models/cars.js + js/models/supercars.js (window.CAR_MODELS)
//   assets/models/bike-<kind>.glb   from js/models/bikes.js (window.BIKE_MODELS)
//   assets/models/robodog.glb       from js/models/robodog.js (window.ROBODOG_MODEL)
//   assets/sprites/<id>.webp        from js/sprites/chars-sheet.js (window.CHAR_SHEETS), byte for byte
//   assets/sprites/<id>.aux.<ext>   from js/sprites/chars-sheet.js (window.CHAR_AUX), byte for byte
//   js/sprites/chars-sheet-files.js the sprite list the page loads (file URLs over http(s), chars-sheet.js from file://)
//
// The GLBs are compressed with EXT_meshopt_compression (decoded in the browser by js/libs/meshopt-decoder.js):
// vertex order optimised, positions quantised to 16 bits, normals to 10 bits (no octahedral filter), UVs to 14 bits; materials, names and
// textures are left exactly as they were (no material dedup: sportsCar() recolours the material named 'paint'). Every quantisation step is
// far below a pixel at the game's camera distances; perf/REPORT.md has the before/after screenshots.
//
// The .js files stay: opened from file:// the browser will not let WebGL use fetched files, so js/asset-files.js falls back to them there.
// Re-run after changing any of the .js packs:  node tools/models-pack.mjs
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { NodeIO } from '@gltf-transform/core';
import { ALL_EXTENSIONS, EXTMeshoptCompression, KHRMeshQuantization } from '@gltf-transform/extensions';
import { reorder, quantize } from '@gltf-transform/functions';
import { MeshoptEncoder } from 'meshoptimizer';

const ROOT = path.dirname(path.dirname(new URL(import.meta.url).pathname));
const at = (...p) => path.join(ROOT, ...p);
const load = (...files) => { const window = {}; const ctx = vm.createContext({ window }); for (const f of files) vm.runInContext(fs.readFileSync(at(f), 'utf8'), ctx, { filename: f }); return window; };

await MeshoptEncoder.ready;
const io = new NodeIO().registerExtensions(ALL_EXTENSIONS).registerDependencies({ 'meshopt.encoder': MeshoptEncoder });

async function packGlb(name, b64) {
  const raw = Buffer.from(b64, 'base64');
  const doc = await io.readBinary(new Uint8Array(raw));
  await doc.transform(
    reorder({ encoder: MeshoptEncoder, target: 'size' }),
    quantize({ quantizePosition: 16, quantizeNormal: 10, quantizeTexcoord: 14, quantizeColor: 8, quantizeWeight: 8, quantizeGeneric: 12 }),
  );
  doc.createExtension(EXTMeshoptCompression).setRequired(true).setEncoderOptions({ method: EXTMeshoptCompression.EncoderMethod.QUANTIZE });
  const out = await io.writeBinary(doc);
  fs.writeFileSync(at('assets/models', name + '.glb'), out);
  return [name, b64.length, out.length];
}

fs.mkdirSync(at('assets/models'), { recursive: true });
fs.mkdirSync(at('assets/sprites'), { recursive: true });
const rows = [];
const m = load('js/models/cars.js', 'js/models/supercars.js', 'js/models/bikes.js', 'js/models/robodog.js');
for (const [k, v] of Object.entries(m.CAR_MODELS)) rows.push(await packGlb('car-' + k, v));
for (const [k, v] of Object.entries(m.BIKE_MODELS)) rows.push(await packGlb('bike-' + k, v));
rows.push(await packGlb('robodog', m.ROBODOG_MODEL));

// sprite sheets: data URIs -> files, unchanged bytes
const s = load('js/sprites/chars-sheet.js');
const sheetIndex = { sheets: {}, aux: {} };
for (const [kind, map] of [['sheets', s.CHAR_SHEETS], ['aux', s.CHAR_AUX]]) for (const [id, uri] of Object.entries(map || {})) {
  const mm = /^data:image\/(\w+);base64,(.*)$/s.exec(uri); if (!mm) throw new Error('not a base64 image: ' + id);
  const file = `${id}${kind === 'aux' ? '.aux' : ''}.${mm[1]}`, bytes = Buffer.from(mm[2], 'base64');
  fs.writeFileSync(at('assets/sprites', file), bytes); sheetIndex[kind][id] = 'assets/sprites/' + file;
  rows.push(['sprite ' + file, uri.length, bytes.length]);
}
// the page's sprite list: over http(s) the files above, from file:// the embedded pack (WebGL refuses images read from file://)
fs.writeFileSync(at('js/sprites/chars-sheet-files.js'), `// the character sprite sheets: over http(s) the WebP files in assets/sprites (byte for byte what chars-sheet.js embeds, without the base64);
// opened from file:// the embedded chars-sheet.js instead, since WebGL will not use an image read from disk. Generated by tools/models-pack.mjs
if (location.protocol === 'file:') document.write('<script src="js/sprites/chars-sheet.js?v=9"><\\/script>');
else {
  window.CHAR_SHEETS = ${JSON.stringify(sheetIndex.sheets)};
  window.CHAR_AUX = ${JSON.stringify(sheetIndex.aux)};
}
`);

let a = 0, b = 0;
for (const [n, x, y] of rows) { a += x; b += y; console.log(n.padEnd(34), String(Math.round(x / 1024)).padStart(7), 'KB ->', String(Math.round(y / 1024)).padStart(6), 'KB'); }
console.log('total'.padEnd(34), String(Math.round(a / 1024)).padStart(7), 'KB ->', String(Math.round(b / 1024)).padStart(6), 'KB');
